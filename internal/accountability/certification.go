package accountability

import (
	"fmt"
	"strings"
	"time"

	"github.com/efij/AgentDFIR/v3/internal/casepkg"
	"github.com/efij/AgentDFIR/v3/internal/custody"
	"github.com/efij/AgentDFIR/v3/internal/seal"
	"github.com/efij/AgentDFIR/v3/internal/version"
)

// CertFields are the human-supplied parts of a certification. Any left
// empty are written as a [[ ]] placeholder for a qualified person to
// complete; the tool never fills them in on anyone's behalf.
type CertFields struct {
	Name  string
	Title string
	Org   string
}

// Certification renders a fill-in certification modelled on US Federal
// Rules of Evidence 902(13) and 902(14): a written declaration by a
// qualified person about how the records were generated and copied, and
// how their integrity can be checked. The case facts (digests, rounds,
// dates, tool version) are filled from the package; the person, their
// qualification and their signature are left for them.
//
// This text is not legal advice and is not a certification by itself: a
// qualified person reads it, confirms each statement against the evidence,
// completes the placeholders and signs. Whether it is accepted anywhere is
// for a court and counsel, not this tool.
func Certification(pkg string, f CertFields) (string, error) {
	man, err := casepkg.ReadManifest(pkg)
	if err != nil {
		return "", err
	}
	ci, err := casepkg.ReadCaseInfo(pkg)
	if err != nil {
		return "", err
	}
	digest := custody.SealDigest(pkg)
	sigLine := "the package is unsigned"
	if sr, err := seal.Verify(pkg, ""); err == nil && sr.Present {
		if sr.Valid {
			sigLine = "a valid ed25519 signature (SEAL.sig) over that seal, made with the key whose public half has fingerprint " + seal.Fingerprint(sr.PublicKey)
		} else {
			sigLine = "an ed25519 signature (SEAL.sig) that does NOT currently verify against the seal"
		}
	}
	ph := func(v, placeholder string) string {
		if strings.TrimSpace(v) == "" {
			return "[[ " + placeholder + " ]]"
		}
		return v
	}
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# Certification of an electronic record (FRE 902(13) / 902(14) model)\n\n")
	w("*Not legal advice. This document is a template. A qualified person must confirm every statement against the evidence, complete each [[ ]] field, and sign. Signing is done by a person, never by the tool. Admissibility is for a court to decide.*\n\n")
	w("I, **%s**, %s at **%s**, declare the following of my own knowledge:\n\n",
		ph(f.Name, "full name of the qualified person"), ph(f.Title, "title / qualification"), ph(f.Org, "organization"))
	w("1. **Qualification.** I am qualified to make this certification because [[ state the basis: role, training, familiarity with the system and the collection process ]].\n\n")
	w("2. **The records.** This certification concerns the AgentDFIR evidence package for case **%s**, collected from host **%s** (%s), created %s.\n\n",
		man.CaseID, man.Host, man.OS+"/"+man.Arch, man.CreatedUTC)
	w("3. **Generated by an electronic process (902(13)).** The records were produced by AI coding-agent software on the host in the normal course of its operation, and were read from the host by AgentDFIR version %s (collector binary SHA-256 %s). AgentDFIR copies files without modifying them, records every artifact's SHA-256, and does not execute the software under investigation.\n\n",
		man.CollectorVersion, orPlaceholder(man.CollectorBinary, "collector binary SHA-256 was not recorded in this package"))
	w("4. **Copied from an electronic device (902(14)).** Each artifact's `artifact_id` is the SHA-256 of its plaintext content, recorded at the time of copying. The complete sealed set is covered by a SHA-256 manifest (`SHA256SUMS`) whose own SHA-256 digest is:\n\n    %s\n\n   The package carries %s.\n\n",
		orPlaceholder(digest, "no seal present"), sigLine)
	w("5. **Collection.** The acquisition was carried out in %d round(s):\n\n", len(ci.Rounds))
	if len(ci.Rounds) == 0 {
		w("   - round 1: created %s (single-round package).\n", man.CreatedUTC)
	}
	for _, r := range ci.Rounds {
		line := fmt.Sprintf("   - round %d: started %s, completed %s, collector %s", r.Round, r.StartedUTC, r.CompletedUTC, r.CollectorVersion)
		if r.Signer != "" {
			line += ", sealed for key " + seal.Fingerprint(r.Signer)
		}
		if r.PriorIntegrity != "" {
			line += ", earlier rounds " + r.PriorIntegrity + " before this one was added"
		}
		w("%s.\n", line)
	}
	w("\n6. **Authority for the acquisition.** ")
	wrote := false
	if ci.Authorization != "" {
		w("The collection recorded authorization reference `%s`. ", ci.Authorization)
		wrote = true
	}
	if recs, _, err := custody.Read(pkg); err == nil {
		for _, a := range custody.Authorizations(recs) {
			w("Recorded by `%s@%s` on %s: authorized by %s on the basis of %q. ",
				a.OSUser, a.Host, a.TS, a.FieldString("by"), a.FieldString("basis"))
			wrote = true
		}
	}
	if !wrote {
		w("[[ state who authorized the acquisition and on what basis ]]. ")
	}
	w("\n\n7. **Integrity can be re-checked.** Anyone can confirm the package is unaltered by re-running `agentdfir verify` on it, or with standard tools: `sha256sum -c SHA256SUMS` inside the package, and (if signed) ed25519 verification of `SEAL.sig` against the manifest digest above. A single changed byte breaks the check.\n\n")
	w("8. **Scope and limits.** This certification concerns the integrity and provenance of the copied records. It does not opine on the meaning of their contents, on whether any action was authorized, or on any legal conclusion. The evidence shows what the host retained; it does not include vendor-side logs or anything deleted before collection.\n\n")
	w("Signed: ______________________________   Date: %s\n\n", ph("", "date"))
	w("Printed name: %s\n\n", ph(f.Name, "full name"))
	w("---\n\nTemplate generated by AgentDFIR %s on %s from the sealed case. Not legal advice; consult counsel in your jurisdiction. Other jurisdictions apply different standards (for example ISO/IEC 27037 for identification, collection, acquisition and preservation).\n",
		version.Version, time.Now().UTC().Format("2006-01-02"))
	return b.String(), nil
}

func orPlaceholder(v, missing string) string {
	if strings.TrimSpace(v) == "" {
		return "[[ " + missing + " ]]"
	}
	return v
}
