// vgText is a volume group in the format vgcfgbackup writes, with the
// extra LV types the fixture adds (../testdata/linux-lvm-extra-lvs.txt).
func vgText(t testing.TB) string {
	t.Helper()
	extra, err := os.ReadFile("../testdata/linux-lvm-extra-lvs.txt")
	if err != nil {
		t.Fatal(err)
	}
	return `# Generated by LVM2
contents = "Text Format Volume Group"
version = 1
vgadfir {
	id = "r5otzE-Pr6y-mudU-JuSI-i60V-3AKa-opPpi0"
	seqno = 4
	status = ["RESIZEABLE", "READ", "WRITE"]
	extent_size = 2048		# 1024 Kilobytes
	physical_volumes {
		pv0 {
			id = "ssUVh5-CKyE-KFwI-iXkx-D4Vt-yNtW-uu4MYj"
			device = "/dev/loop0"	# Hint only
			pe_start = 2048
			pe_count = 17
		}
		pv1 {
			id = "tdZnFk-hkDn-LiFA-oJv5-QPVd-HHjP-hqxj0h"
			pe_start = 2048
			pe_count = 20
		}
	}
	logical_volumes {
		root {
			status = ["READ", "WRITE", "VISIBLE"]
			segment_count = 2
			segment1 {
				start_extent = 0
				extent_count = 4
				type = "striped"
				stripe_count = 1	# linear
				stripes = [
					"pv0", 0
				]
			}
			segment2 {
				start_extent = 4
				extent_count = 2
				type = "striped"
				stripe_count = 1
				stripes = [
					"pv0", 6
				]
			}
		}
` + string(extra) + `
	}
}
`
}

func TestModel(t *testing.T) {
	top, err := Parse(vgText(t))
	if err != nil {
		t.Fatal(err)
	}
	if top["contents"] != "Text Format Volume Group" || top["version"] != int64(1) {
		t.Errorf("top-level scalars %v", top)
	}
	vg, err := Model(top)
	if err != nil {
		t.Fatal(err)
	}
	if vg.Name != "vgadfir" || vg.ExtentSize != 1<<20 || vg.Seqno != 4 || len(vg.PVs) != 2 {
		t.Fatalf("vg %+v", vg)
	}
	if vg.PVs["pv0"].UUID != "ssUVh5CKyEKFwIiXkxD4VtyNtWuu4MYj" || vg.PVs["pv0"].PEStart != 1<<20 {
		t.Errorf("pv0 %+v", vg.PVs["pv0"])
	}
	got := map[string]string{}
	for _, lv := range vg.LVs {
		if lv.Visible {
			got[lv.Name] = lv.Unsupported
		}
	}
	if got["root"] != "" || !strings.Contains(got["thin"], "thin") || !strings.Contains(got["mirror"], "raid1") ||
		!strings.Contains(got["snap"], "snapshot") || !strings.Contains(got["pool"], "thin-pool") {
		t.Errorf("LVs %v", got)
	}
	if _, ok := got["mirror_rimage_0"]; ok {
		t.Error("hidden LV reported visible")
	}
}

func TestParseErrors(t *testing.T) {
	for _, s := range []string{"vg {", "vg { a = }", "vg { a = [1, 2 }", `vg { a = "x }`, "}", "a b c", "vg { a = @ }"} {
		if _, err := Parse(s); err == nil {
			t.Errorf("%q parsed", s)
		}
	}
	deep := strings.Repeat("a {", 100) + strings.Repeat("}", 100)
	if _, err := Parse(deep); err == nil {
		t.Error("deep nesting parsed")
	}
	if _, err := Model(Section{"vg": Section{"extent_size": int64(0)}}); err == nil {
		t.Error("zero extent size accepted")
	}
}

func label(pvuuid string) []byte {
	b := make([]byte, 2048)
	s := b[512:1024]
	copy(s, labelMagic)
	binary.LittleEndian.PutUint64(s[8:], 1)
	binary.LittleEndian.PutUint32(s[20:], 32)
	copy(s[24:], labelType)
	copy(s[32:], pvuuid)
	binary.LittleEndian.PutUint64(s[64:], 1<<20)
	binary.LittleEndian.PutUint64(s[72:], 1<<20) // data area
	binary.LittleEndian.PutUint64(s[104:], 4096) // metadata area
	binary.LittleEndian.PutUint64(s[112:], 1<<19)
	binary.LittleEndian.PutUint32(s[16:], crc(s[20:]))
	return b
}

func TestReadLabel(t *testing.T) {
	b := label("ssUVh5CKyEKFwIiXkxD4VtyNtWuu4MYj")
	pv, err := ReadLabel(bytes.NewReader(b), int64(len(b)))
	if err != nil {
		t.Fatal(err)
	}
	if pv.UUID != "ssUVh5CKyEKFwIiXkxD4VtyNtWuu4MYj" || len(pv.Data) != 1 || len(pv.Metadata) != 1 || pv.Metadata[0].Offset != 4096 {
		t.Fatalf("pv %+v", pv)
	}
	b[600] ^= 1
	if _, err := ReadLabel(bytes.NewReader(b), int64(len(b))); err == nil || !strings.Contains(err.Error(), "checksum") {
		t.Fatalf("bad crc: %v", err)
	}
	if _, err := ReadLabel(bytes.NewReader(make([]byte, 4096)), 4096); err != ErrNoLabel {
		t.Fatalf("no label: %v", err)
	}
	if _, err := ReadMetadata(bytes.NewReader(b), int64(len(b)), pv); err == nil {
		t.Fatal("metadata area past the end read")
	}
}

func FuzzParse(f *testing.F) {
	f.Add(vgText(f))
	f.Add("a = [1,2,\"x\"]\nb { c = 3 }")
	f.Fuzz(func(t *testing.T, s string) {
		top, err := Parse(s)
		if err != nil {
			return
		}
		Model(top)
	})
}

