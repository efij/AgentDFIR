// Markdown renders docs/atlas-coverage.md. The output is deterministic (no
// dates, sorted rows) so a golden test can hold the committed page to it.
func (r Report) Markdown() string {
	var b strings.Builder
	s := r.Summary
	b.WriteString("# MITRE ATLAS coverage\n\n")
	b.WriteString("<!-- GENERATED by `agentdfir rules coverage --format md` from internal/mitre/data/atlas-relevance.json. Do not edit; TestCoverageDocCurrent fails when this page drifts. -->\n\n")
	fmt.Fprintf(&b, "Every technique in MITRE ATLAS %s, classified for what an offline endpoint and AI-agent forensic tool can observe, with the rules and chains that answer it. ", r.ATLASVersion)
	fmt.Fprintf(&b, "ATT&CK references elsewhere are validated against ATT&CK Enterprise v%s; OWASP references use %s.\n\n", r.ATTACKVersion, strings.Join(r.OWASP, " and "))
	b.WriteString("| | |\n|---|---|\n")
	fmt.Fprintf(&b, "| ATLAS techniques classified | **%d / %d** |\n", s.Classified, s.Techniques)
	fmt.Fprintf(&b, "| direct / supporting / unobservable / out of scope | %d / %d / %d / %d |\n", s.Direct, s.Supporting, s.Unobservable, s.OutOfScope)
	fmt.Fprintf(&b, "| P0 / P1 / P2 | %d / %d / %d |\n", s.P0, s.P1, s.P2)
	fmt.Fprintf(&b, "| Covered (a rule or chain is mapped) | **%d** |\n", s.Covered)
	fmt.Fprintf(&b, "| Validated (covered, and a named test exercises it) | **%d** |\n", s.Validated)
	fmt.Fprintf(&b, "| P0 observable techniques covered | %d / %d |\n", s.P0Covered, s.P0Observable)
	fmt.Fprintf(&b, "| Techniques with detections still being added (planned) | %d |\n", s.Planned)
	fmt.Fprintf(&b, "| P0 observable techniques with a documented exception | %d |\n\n", s.Exceptions)
	b.WriteString(`How to read this page:

- **direct**: the technique itself leaves evidence AgentDFIR reads (agent transcripts, MCP gateway logs, configuration snapshots, endpoint telemetry, cloud audit logs, git).
- **supporting**: only a precursor or an effect is observable; the rules listed catch that step, not the technique as a whole.
- **unobservable**: in scope, but it leaves nothing AgentDFIR collects. Listed so the gap is explicit.
- **out of scope**: happens on adversary infrastructure, public services, model training or inference internals, or in the physical world.
- **Covered** means a rule or chain is mapped, not that every variant is detected. A missing finding is never proof the technique did not happen.
- **P0**: exfiltration, credential theft, unauthorized execution, tool poisoning, privilege escalation, destructive impact, evidence tampering. Every P0 observable technique has a rule, a chain, a planned detection, or a written exception.

Reproduce: ` + "`agentdfir rules coverage` (table), `--json` (machine-readable), `--format md` (this page).\n\n")

	b.WriteString("## Observable and in-scope techniques\n\n")
	b.WriteString("| Technique | Name | Class | Priority | Rules / chains | Evidence | Tests | OWASP | Limitation / exception |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|\n")
	for _, t := range r.Techniques {
		if t.Class == mitre.ClassOutOfScope {
			continue
		}
		det := codeList(append(append([]string{}, t.Rules...), t.Chains...))
		if len(t.Planned) > 0 {
			if det != "" {
				det += "<br>"
			}
			det += "planned: " + codeList(t.Planned)
		}
		lim := t.Limitation
		if t.Exception != "" {
			lim += "<br>**Exception:** " + t.Exception
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s | %s | %s | %s |\n",
			t.ID, cell(t.Name), t.Class, dash(t.Priority), dash(det), dash(cell(strings.Join(t.Evidence, ", "))),
			dash(codeList(t.Tests)), dash(strings.Join(t.OWASP, ", ")), cell(lim))
	}
	b.WriteString("\n## Out-of-scope techniques\n\n")
	b.WriteString("| Technique | Name | Why |\n|---|---|---|\n")
	for _, t := range r.Techniques {
		if t.Class != mitre.ClassOutOfScope {
			continue
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", t.ID, cell(t.Name), cell(t.Limitation))
	}
	return b.String()
}

// Text renders the terminal table of `agentdfir rules coverage`.
func (r Report) Text() string {
	var b strings.Builder
	fmt.Fprintf(&b, "%-14s %-12s %-3s %-5s %-6s %s\n", "ATLAS", "CLASS", "PRI", "DET", "TESTS", "NAME")
	for _, t := range r.Techniques {
		det := fmt.Sprintf("%d", len(t.Rules)+len(t.Chains))
		if len(t.Planned) > 0 {
			det += "+"
		}
		if t.Exception != "" {
			det = "exc"
		}
		fmt.Fprintf(&b, "%-14s %-12s %-3s %-5s %-6d %s\n", t.ID, t.Class, dash(t.Priority), det, len(t.Tests), t.Name)
	}
	s := r.Summary
	fmt.Fprintf(&b, "\nATLAS %s: %d/%d classified (%d direct, %d supporting, %d unobservable, %d out of scope); %d P0, %d P1, %d P2.\n",
		r.ATLASVersion, s.Classified, s.Techniques, s.Direct, s.Supporting, s.Unobservable, s.OutOfScope, s.P0, s.P1, s.P2)
	fmt.Fprintf(&b, "%d covered, %d validated by a named test, %d with planned detections, %d P0 exceptions. P0 observable covered: %d/%d.\n",
		s.Covered, s.Validated, s.Planned, s.Exceptions, s.P0Covered, s.P0Observable)
	b.WriteString("DET: mapped rules+chains (+ = more planned, exc = documented exception). Covered is a mapping, not proof every variant is detected.\n")
	return b.String()
}

func codeList(ids []string) string {
	if len(ids) == 0 {
		return ""
	}
	out := make([]string, len(ids))
	for i, id := range ids {
		out[i] = "`" + id + "`"
	}
	return strings.Join(out, ", ")
}

// cell keeps free text from breaking a Markdown table row.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}
